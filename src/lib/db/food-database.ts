export function searchFoodDatabase(query: string, categoryFilter?: string): DatabaseFoodItem[] {
  if (!query || query.trim().length === 0) {
    if (categoryFilter && categoryFilter !== "All") {
      return FOOD_DATABASE.filter(f => f.category === categoryFilter);
    }
    return FOOD_DATABASE.slice(0, 12);
  }

  const q = query.toLowerCase().trim();

  return FOOD_DATABASE.filter((item) => {
    const matchesCategory = !categoryFilter || categoryFilter === "All" || item.category === categoryFilter;
    const matchesText =
      item.name.toLowerCase().includes(q) ||
      (item.brand && item.brand.toLowerCase().includes(q)) ||
      (item.barcode && item.barcode.includes(q)) ||
      item.keywords.some((kw) => kw.toLowerCase().includes(q)) ||
      item.ingredients.some((ing) => ing.toLowerCase().includes(q));

    return matchesCategory && matchesText;
  });
}

export function findFoodByBarcode(barcode: string): DatabaseFoodItem | undefined {
  return FOOD_DATABASE.find((item) => item.barcode === barcode);
}
